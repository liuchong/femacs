#!/usr/bin/env python3
"""Write the `R` class the Kotlin targets need, from the reference's own `res/` tree.

Every Kotlin target that names a resource (`R.drawable.emacs`, `R.string.start_quick_title`, ...)
cannot compile without `R`, and `R` is normally generated by aapt from `res/`.  This is that
generation reduced to what a *compile* needs: one `const val` per resource name, and the same
names and the same nesting aapt would produce.

    spikes/android-r-from-res.py > R.kt

Names come from the tree (`drawable/emacs.png` -> `R.drawable.emacs`; `layout/x.xml` ->
`R.layout.x`; `mipmap-v26/y.xml` -> `R.mipmap.y`), from the value files (`<string name="a">` ->
`R.string.a`; `<item type="id" name="b">` -> `R.id.b`) and from the `@+id/...` references any
XML under `res/` writes (`android:id="@+id/name"`
in a layout -> `R.id.name`).  That third source is the one `EmacsDesktopNotification.java` needs:
its two ids live only inside `res/layout/sdk8_notifications_view.xml`, and this generator read
value files alone until 3.348, so `R.id` did not exist at all (the probe failed with an unresolved
reference on `R.id.sdk8_notifications_title`).  The *values* are all zero: a real `R`
carries aapt's ids, and nothing here runs, so the numbers would be invented rather than read
(P-83 ⑥'s compile check only needs the shape).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
RES = REPO / "emacs" / "java" / "res"
# aapt's plural for the XML tags; a tag not listed here is reported instead of guessed.
TAG_TYPES = {"string": "string", "bool": "bool", "integer": "integer", "color": "color",
             "dimen": "dimen", "style": "style", "array": "array", "string-array": "array",
             "integer-array": "array", "attr": "attr", "plurals": "plurals"}


def main() -> int:
    entries: dict[str, set[str]] = {}
    unknown: list[str] = []
    import xml.etree.ElementTree as ET

    for path in sorted(RES.rglob("*")):
        if not path.is_file():
            continue
        parts = path.relative_to(RES).parts
        kind = parts[0].split("-")[0]
        if kind == "values":
            # Only the direct children of <resources> define resources: an <item> inside a <style>
            # is a style attribute, not a name (that distinction is why this parses rather than
            # greps).
            root = ET.parse(path).getroot()
            for child in root:
                name = child.get("name")
                if name is None:
                    continue
                tag = child.get("type") if child.tag == "item" else child.tag
                if tag in TAG_TYPES:
                    entries.setdefault(TAG_TYPES[tag], set()).add(name)
                else:
                    unknown.append(f"{path}: <{child.tag} name={name!r}> is not a type this "
                                   f"generator knows")
        else:
            entries.setdefault(kind, set()).add(path.stem)
            # `@+id/NAME` in *any* XML file under res/ defines an id (aapt's rule).  The two
            # `EmacsDesktopNotification` needs are declared only inside a layout, and until 3.348
            # this generator read value files alone - so `R.id` did not exist and the probe failed
            # with an unresolved reference on `R.id.sdk8_notifications_title`.
            if path.suffix == ".xml":
                for name in re.findall (r'@\+id/([A-Za-z_][A-Za-z0-9_]*)',
                                       path.read_text (encoding="utf-8", errors="replace")):
                    entries.setdefault ("id", set()).add (name)
    out = ["// Generated from emacs/java/res by spikes/android-r-from-res.py - the `R` class the",
           "// Kotlin targets compile against.  Ids are zero: only the names and the nesting are read",
           "// from the reference (see the tool's docstring).",
           "package org.femacs", "", "object R {"]
    for kind in sorted(entries):
        out.append(f"  object {kind} {{")
        for name in sorted(entries[kind]):
            out.append(f"    const val {name} = 0")
        out.append("  }")
    out.append("}")
    print("\n".join(out))
    for line in unknown:
        print(line, file=sys.stderr)
    return 1 if unknown else 0


if __name__ == "__main__":
    raise SystemExit(main())
