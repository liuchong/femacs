#!/usr/bin/env python3
"""Turn femacs/lib/include/mini-gmp.rs's declarations back into C, as an ABI harness.

The mirror maps a 314-line header with 159 prototypes by hand, and the pair's checklist
has no function *definitions* (`--check` therefore sees only the macros and the one
file-scope object).  This tool reads the mirror, reverses the type mapping and prints

    static RET (*p_NAME) (ARGS) = NAME;

for every declaration, so `clang -Werror=incompatible-pointer-types` against the reference
`emacs/lib/mini-gmp.h` turns any wrong width / const-ness / return type into an error
(review B's technique, applied to the whole header; see spikes/gmp-abi-probe.sh).

    python3 tools/gen-gmp-abi-probe.py > build/gmp-abi-probe/harness.c
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

MIRROR = Path("femacs/lib/include/mini-gmp.rs")

FN1 = 'unsafe extern "C" fn (usize) -> *mut c_void'
FN2 = 'unsafe extern "C" fn (*mut c_void, usize, usize) -> *mut c_void'
FN3 = 'unsafe extern "C" fn (*mut c_void, usize)'
C_FN1 = "void *(*) (size_t)"
C_FN2 = "void *(*) (void *, size_t, size_t)"
C_FN3 = "void (*) (void *, size_t)"

# Rust -> C, longest spellings first.
RULES = [
    (f"*mut Option<{FN1}>", "void *(**) (size_t)"),
    (f"*mut Option<{FN2}>", "void *(**) (void *, size_t, size_t)"),
    (f"*mut Option<{FN3}>", "void (**) (void *, size_t)"),
    (FN1, C_FN1),
    (FN2, C_FN2),
    (FN3, C_FN3),
    # The pointer typedefs, not the array typedef: `const mpz_t` as a *return* type is an
    # array type, which C rejects ("function cannot return array type").
    ("*const __mpz_struct", "mpz_srcptr"),
    ("*mut __mpz_struct", "mpz_ptr"),
    ("*const mp_limb_t", "mp_srcptr"),
    ("*mut mp_limb_t", "mp_ptr"),
    ("*const c_char", "const char *"),
    ("*mut c_char", "char *"),
    ("*const u8", "const unsigned char *"),
    ("*mut u8", "unsigned char *"),
    ("*const c_void", "const void *"),
    ("*mut c_void", "void *"),
    ("*mut usize", "size_t *"),
    ("*mut FILE", "FILE *"),
    ("c_int", "int"),
    ("c_uint", "unsigned int"),
    ("c_long", "long"),
    ("c_ulong", "unsigned long"),
    ("c_double", "double"),
    ("mp_limb_t", "mp_limb_t"),
    ("mp_size_t", "mp_size_t"),
    ("mp_bitcnt_t", "mp_bitcnt_t"),
    ("usize", "size_t"),
]


def split_top_level(args: str) -> list:
    """Split a parameter list on commas that are not inside parentheses."""
    out, depth, cur = [], 0, ""
    for ch in args:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur)
            cur = ""
            continue
        cur += ch
    if cur.strip():
        out.append(cur)
    return out


def to_c(rust_type: str) -> str:
    t = rust_type.strip()
    if t == "()":
        return "void"
    for pat, rep in RULES:
        t = t.replace(pat, rep)
    leftovers = [w for w in ("unsafe", "extern", "Option", "->", "<", ">") if w in t]
    if leftovers:
        raise SystemExit(f"unmapped Rust type {rust_type!r} (leftovers: {leftovers})")
    return t


def main() -> int:
    text = MIRROR.read_text(encoding="utf-8")
    print("/* Generated by tools/gen-gmp-abi-probe.py from femacs/lib/include/mini-gmp.rs;")
    print("   do not edit.  Every line is a C declaration whose type must equal the")
    print("   reference header's (spikes/gmp-abi-probe.sh compiles it).  */")
    print("#include <stddef.h>")
    print("#include <stdio.h>")
    print("#include \"mini-gmp.h\"")
    print()
    names = []
    # The parameter list is balanced-scanned, not regex-matched: a function-pointer
    # parameter (`unsafe extern "C" fn (usize) -> *mut c_void`) contains parens, so a
    # non-greedy `\(([^;]*?)\)` cut the declaration at the first `)`.
    for m in re.finditer(r"pub fn (\w+)\s*\(", text):
        name = m.group(1)
        depth, i = 0, m.end() - 1
        while i < len(text):
            if text[i] == "(":
                depth += 1
            elif text[i] == ")":
                depth -= 1
                if depth == 0:
                    break
            i += 1
        args = text[m.end():i].strip()
        tail = text[i + 1:]
        ret = "()"
        arrow = re.match(r"\s*->\s*", tail)
        if arrow:
            stop = tail.index(";", arrow.end())
            ret = tail[arrow.end():stop].strip()
        ret_c = to_c(ret)
        params = []
        if args:
            for arg in split_top_level(args):
                _, _, ty = arg.partition(":")
                params.append(to_c(ty))
        print(f"static {ret_c} (*p_{name}) ({', '.join(params) or 'void'}) = {name};")
        names.append(name)
    print()
    print("int main (void)")
    print("{")
    for name in names:
        print(f"  (void) p_{name};")
    print(f"  printf (\"gmp declarations checked %zu\\n\", (size_t) {len(names)});")
    print("  return 0;")
    print("}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
