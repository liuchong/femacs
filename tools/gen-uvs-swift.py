#!/usr/bin/env python3
"""Generate the Swift data fragment for `src/macuvs.h` (docs/ports/macfont.md, decision 1).

`src/macfont.m` reads one UVS table, `mac_uvs_table_adobe_japan1_bytes` (`src/macuvs.h` 9-9218,
73,655 bytes), as the Adobe-Japan1 fallback of `macfont_get_uvs_table`.  The Swift port carries
that table **as Swift data** - no runtime file reads, no resource bundle - and this generator
writes the fragment, because the table is far too large to spell by hand.

    python3 tools/gen-uvs-swift.py                 # print the fragment
    python3 tools/gen-uvs-swift.py --check         # compare with the copy in macfont.swift
    python3 tools/gen-uvs-swift.py --write         # rewrite the copy inside macfont.swift

The fragment is one `fileprivate let` array built from fixed-size literal chunks (a single
73,655-element literal is what the Swift type checker chokes on; the chunks are the same values
in the same order, joined by `+`, which the compiler folds).

The output is byte-for-byte reproducible from `emacs/src/macuvs.h`; the ledger records the
command and the C line span.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
C_SOURCE = REPO / "emacs" / "src" / "macuvs.h"
SWIFT = REPO / "femacs" / "platform" / "macos" / "macfont.swift"

BEGIN = "// gen-uvs-swift: begin"
END = "// gen-uvs-swift: end"
CHUNK = 4096
PER_LINE = 12


def read_bytes() -> tuple[list[int], int, int]:
    text = C_SOURCE.read_text(encoding="utf-8")
    m = re.search(r"static const unsigned char (\w+)\[\]\s*=\s*\{(.*?)\n\s*\};", text, re.S)
    if not m:
        sys.exit("gen-uvs-swift: %s: the array was not found" % C_SOURCE)
    name = m.group(1)
    start = text[: m.start()].count("\n") + 1
    end = text[: m.end()].count("\n") + 1
    values = [int(v, 16) for v in re.findall(r"0x([0-9a-fA-F]{1,2})", m.group(2))]
    if name != "mac_uvs_table_adobe_japan1_bytes":
        sys.exit("gen-uvs-swift: unexpected array name %s" % name)
    return values, start, end


def fragment(values: list[int], start: int, end: int) -> str:
    lines = [
        BEGIN,
        "/// C: `static const unsigned char mac_uvs_table_adobe_japan1_bytes[] = { … };`",
        "/// (src/macuvs.h %d-%d; %d values)." % (start, end, len(values)),
        "///",
        "/// Generated by `python3 tools/gen-uvs-swift.py` from `emacs/src/macuvs.h`; do not edit",
        "/// by hand (re-run the generator).  The Adobe-Japan1 UVS table the deferred fallback of",
        "/// `macfont_get_uvs_table` reads, carried as Swift data: no runtime file read and no",
        "/// resource bundle (docs/ports/macfont.md, decision 1).",
        "fileprivate let mac_uvs_table_adobe_japan1_bytes: [UInt8] = [",
    ]
    chunks = [values[i : i + CHUNK] for i in range(0, len(values), CHUNK)]
    for ci, chunk in enumerate(chunks):
        if ci:
            lines.append("  ] + [")
        for i in range(0, len(chunk), PER_LINE):
            row = chunk[i : i + PER_LINE]
            lines.append("  " + " ".join("0x%02x," % v for v in row))
    lines.append("  ]")
    lines.append(END)
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true", help="rewrite the copy inside macfont.swift")
    ap.add_argument("--check", action="store_true", help="compare with the copy in macfont.swift")
    args = ap.parse_args()

    values, start, end = read_bytes()
    text = fragment(values, start, end)
    if not (args.write or args.check):
        sys.stdout.write(text)
        return 0

    swift = SWIFT.read_text(encoding="utf-8")
    if args.check:
        m = re.search(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n", swift, re.S)
        if not m:
            sys.exit("gen-uvs-swift --check: no generated block in %s" % SWIFT)
        if m.group(0) != text:
            sys.exit("gen-uvs-swift --check: the block in %s is stale" % SWIFT)
        print("gen-uvs-swift --check: %s block matches src/macuvs.h (%d values)"
              % (SWIFT.name, len(values)))
        return 0

    m = re.search(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n", swift, re.S)
    if m:
        swift = swift[: m.start()] + text + swift[m.end() :]
    else:
        swift = swift.rstrip("\n") + "\n\n" + text
    SWIFT.write_text(swift, encoding="utf-8")
    print("gen-uvs-swift --write: %s <- emacs/src/macuvs.h (%d values, %d chunks)"
          % (SWIFT.name, len(values), (len(values) + CHUNK - 1) // CHUNK))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
