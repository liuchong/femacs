#!/usr/bin/env python3
"""Check every ported .rs against the map's name for it (docs/port-map.md, generated).

Two things can go wrong with a file's *name*, and neither shows up as a compile error,
a `--check` failure, or a `todo` row anyone reads twice:

  R1  a file that no row of `docs/port-inventory.md` points at.  Either the map's naming
      rule and the file disagree, or the file is not a port at all.  The 27 system-header
      mirrors (`<stdio.h>`, `<errno.h>`, `<sys/select.h>`, ...), the three generated
      aggregates (`config.rs`, `globals.rs`, `buildobj.rs`), `gnulib_config.rs`, the four
      `.rs` files the verbatim trees carry and `xtask` itself are the declared exceptions,
      and each says so on its first line; everything else is a finding.
  R2  a file whose own first line names a reference file (`// femacs: port of X @ rev`,
      `// femacs: mirror of X @ rev`) that the map does not send to this path.  This is the
      class status 3.139 fixed by hand: `getopt-cdefs.rs` was the mirror of
      `lib/getopt-cdefs.in.h` while the map asks for `getopt-cdefs.in.rs`, so the file was in
      the tree, `--check` was OK, and the row could only ever read `todo` - the DoD's first
      line ("590 all ported") was unreachable while that name stood.

    python3 tools/check-target-names.py            # the two rules above
    python3 tools/check-target-names.py --selftest # prove the classifiers on known shapes
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
MAP = REPO / "docs/port-inventory.md"
# Trees copied byte-for-byte from the reference (check-verbatim guards them) and this
# project's own build driver: not ports, so no row and no rule applies.
SKIP_DIRS = ("femacs/lisp/", "femacs/test/", "femacs/etc/", "femacs/doc/",
             "femacs/leim/", "femacs/admin/", "femacs/xtask/")
# First lines that say "this file is not a port of a reference file, on purpose".
DECLARED = (
    re.compile(r"^// femacs: mirror of the frozen target's <"),
    re.compile(r"^// femacs: the parts of the (?:system|frozen target's) <"),
    re.compile(r"^// femacs: the <[^>]+> declarations "),
    re.compile(r"^// femacs: the gnulib configuration macros the port needs"),
    re.compile(r"^// femacs: generated mirror of the frozen build's"),
    re.compile(r"^// Generated by `xtask "),
)
# `// femacs: port of src/x.c @ rev` / `// femacs: WIP mirror of lib/x.in.h @ rev ...`
PROVENANCE = re.compile(r"^// femacs: (?:WIP )?(?:port|mirror) of (\S+) @")


def read_map() -> dict[str, str]:
    """reference path -> target path, straight from the generated inventory."""
    out: dict[str, str] = {}
    for line in MAP.read_text(encoding="utf-8").splitlines():
        parts = line.split("|")
        if len(parts) < 12:
            continue
        ref = parts[1].strip().strip("`")
        tgt = parts[10].strip().strip("`")
        if tgt and re.match(r"^(src|lib|lib-src|lwlib|oldXMenu|exec|nt|msdos)/", ref):
            out[ref] = tgt
    return out


def classify(rel: str, first_line: str, targets: set[str], path_of: dict[str, str]):
    """Return None when the file is fine, else (rule, message)."""
    if rel in targets:
        if (m := PROVENANCE.match(first_line)):
            ref = m.group(1)
            if ref in path_of and path_of[ref] != rel:
                return ("R2", f"names {ref}, whose map target is {path_of[ref]}")
            if ref not in path_of:
                return ("R2", f"names {ref}, which has no row in the map")
        return None
    if any(rel.startswith(d) for d in SKIP_DIRS):
        return None
    if any(r.match(first_line) for r in DECLARED):
        return None
    if (m := PROVENANCE.match(first_line)):
        ref = m.group(1)
        want = path_of.get(ref, "<no row>")
        return ("R1", f"is a port of {ref} but the map asks for {want}")
    return ("R1", "no map row points at this file, and its first line does not declare it a "
                  "system-header mirror or a generated artifact")


def walk() -> list[str]:
    return sorted(str(p.relative_to(REPO))
                  for p in (REPO / "femacs").rglob("*.rs")
                  if "target/" not in str(p.relative_to(REPO)))


def selftest() -> int:
    ok = True
    targets = {"femacs/src/alloc.rs"}
    path_of = {"src/alloc.c": "femacs/src/alloc.rs", "lib/getopt-cdefs.in.h":
               "femacs/lib/include/getopt-cdefs.in.rs"}
    cases = [
        ("femacs/src/alloc.rs", "// femacs: port of src/alloc.c @ fd7afced403.", None),
        ("femacs/lib/include/getopt-cdefs.rs",
         "// femacs: WIP mirror of lib/getopt-cdefs.in.h @ fd7afced403 (the generated", "R1"),
        ("femacs/src/alloc.rs", "// femacs: port of src/other.c @ fd7afced403.", "R2"),
        ("femacs/lib/include/stdio.rs",
         "// femacs: mirror of the frozen target's <stdio.h> (system header, P-26/P-50).", None),
        ("femacs/lib/include/gnulib_config.rs",
         "// femacs: the gnulib configuration macros the port needs, in one place (PORTING.md 0.1-5)",
         None),
        ("femacs/src/include/config.rs",
         "// Generated by `xtask gen-config` from the frozen configuration; do not edit.", None),
        ("femacs/lisp/subr.el.rs", ";; not a port", None),
        ("femacs/src/mystery.rs", "// femacs: something else entirely", "R1"),
    ]
    for rel, first, want in cases:
        got = classify(rel, first, targets, path_of)
        rule = None if got is None else got[0]
        flag = "ok  " if rule == want else "FAIL"
        if rule != want:
            ok = False
        print(f"{flag} {rel} -> {rule}")
    print(f"{len(cases)} cases, {0 if ok else 1} failures")
    return 0 if ok else 1


def main() -> int:
    if "--selftest" in sys.argv[1:]:
        return selftest()
    path_of = read_map()
    targets = set(path_of.values())
    findings = []
    for rel in walk():
        p = REPO / rel
        try:
            first = p.read_text(encoding="utf-8", errors="replace").split("\n", 1)[0]
        except OSError as exc:
            findings.append(("R0", rel, str(exc)))
            continue
        got = classify(rel, first, targets, path_of)
        if got is not None:
            findings.append((got[0], rel, got[1]))
    for rule, rel, msg in findings:
        print(f"{rule}\t{rel}\t{msg}")
    print(f"check-target-names: {len(walk())} .rs files, {len(targets)} map targets, "
          f"{len(findings)} finding(s)")
    return 1 if findings else 0


if __name__ == "__main__":
    sys.exit(main())
