#!/bin/sh
# Type-check the Android Kotlin shell against the platform's android.jar - offline.
#
# `docs/port-plan.md`'s platform row and DoD-6 need the Android leg to build.  The Kotlin
# sources (`femacs/platform/android/**/*.kt`, the port of `java/**/*.java`) do not need a full
# Android build to be *checked*: Android Studio ships a Kotlin compiler and a JDK, and the SDK
# ships `android.jar`, so the compile can run with nothing downloaded and nothing installed.
#
#   tools/check-android-kotlin.sh              # compile to a temp dir, print the class count
#   tools/check-android-kotlin.sh --keep DIR   # keep the output classes in DIR
#   tools/check-android-kotlin.sh --apk DIR    # also assemble and sign an APK in DIR
#
# `--apk` runs the rest of `emacs/java/Makefile.in`'s packaging: `d8` turns the classes into
# `classes.dex`, `aapt2 link`'s archive and that dex are zipped into an APK, and `apksigner`
# signs it with a debug key `keytool` generates once.  The APK is built *without* the native
# libraries, which the port's Android native build will add (P-201); everything else is real.
#
# Environment overrides (all optional): STUDIO (the Android Studio bundle), ANDROID_HOME,
# ANDROID_API (default android-36).  Exit status is the compiler's.
set -u
REPO=$(cd "$(dirname "$0")/.." && pwd)
STUDIO=${STUDIO:-/Applications/Android Studio.app/Contents}
ANDROID_HOME=${ANDROID_HOME:-$HOME/Library/Android/sdk}
ANDROID_API=${ANDROID_API:-android-36}
OUT=""
OUT=""
KEEP=""
while [ $# -gt 0 ]; do
  case "$1" in
    --keep) KEEP=$2; shift 2 ;;
    --apk)  APK_DIR=$2; shift 2 ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done
OUT=""
APK_DIR=${APK_DIR:-}

# Android Studio ships the complete CLI compiler (not just the IDE plugin): `kotlinc` next to
# its own JDK, which is all this check needs.
JAVA_HOME=${JAVA_HOME:-$STUDIO/jbr/Contents/Home}
KOTLINC="$STUDIO/plugins/Kotlin/kotlinc/bin/kotlinc"
STDLIB="$STUDIO/plugins/Kotlin/kotlinc/lib/kotlin-stdlib.jar"
ANDROID_JAR="$ANDROID_HOME/platforms/$ANDROID_API/android.jar"
AAPT2=$(ls "$ANDROID_HOME"/build-tools/*/aapt2 2>/dev/null | tail -1)

for f in "$KOTLINC" "$STDLIB" "$ANDROID_JAR" "$AAPT2"; do
  if [ ! -f "$f" ]; then
    echo "missing: $f" >&2
    echo "the Android leg needs Android Studio (for kotlinc and a JDK) and the SDK's $ANDROID_API" >&2
    exit 2
  fi
done

[ -n "$KEEP" ] && OUT=$KEEP
[ -n "$OUT" ] || OUT=$(mktemp -d /tmp/femacs-kt.XXXXXX)
mkdir -p "$OUT"

# `R` is generated by aapt2 from the manifest and `res/`, and the Kotlin sources use it, so the
# resource link runs first and its R.jar joins the classpath (P-199: without it every `R.style…`
# is an unresolved reference).
GEN="$OUT/gen"
mkdir -p "$GEN"
RES_ZIP="$OUT/res.zip"
"$AAPT2" compile --dir "$REPO/femacs/platform/android/res" -o "$RES_ZIP" || exit $?
"$AAPT2" link -o "$OUT/resources.ap_" -I "$ANDROID_JAR" \
  --manifest "$REPO/femacs/platform/android/AndroidManifest.xml" --java "$GEN" "$RES_ZIP" || exit $?
mkdir -p "$OUT/rclasses"
R_JAVA=$(find "$GEN" -name R.java | head -1)
[ -n "$R_JAVA" ] || { echo "aapt2 did not write R.java" >&2; exit 3; }
"$JAVA_HOME/bin/javac" -classpath "$ANDROID_JAR" -d "$OUT/rclasses" "$R_JAVA" || exit $?
(cd "$OUT/rclasses" && "$JAVA_HOME/bin/jar" cf "$OUT/R.jar" .) || exit $?
R_JAR="$OUT/R.jar"
echo "resources: R.jar built from $(find "$REPO/femacs/platform/android/res" -type f | wc -l | tr -d ' ') resource file(s)"

# The reference generates a class at build time (`EmacsConfig`, java/Makefile.in 411-424); the
# Kotlin sources name it, so the generator runs first and its file joins the compilation.
mkdir -p "$OUT/generated"
python3 "$REPO/tools/gen-emacs-config.py" --out "$OUT/generated" || exit $?

FILES=$(find "$REPO/femacs/platform/android" "$OUT/generated" -name '*.kt' | sort)
COUNT=$(printf '%s\n' "$FILES" | grep -c .)
echo "compiling $COUNT Kotlin file(s) against $ANDROID_JAR"
# shellcheck disable=SC2086
# No `-no-stdlib`: the compiler's own standard library is what the sources expect, and it is
# part of the bundled kotlinc (passing `-no-stdlib` without a replacement makes every
# `kotlin.String` unreachable - measured).
JAVA_HOME="$JAVA_HOME" "$KOTLINC" -classpath "$ANDROID_JAR:$R_JAR" -d "$OUT" $FILES
status=$?
classes=$(find "$OUT" -name '*.class' | wc -l | tr -d ' ')
echo "kotlin: exit $status, $classes class file(s) in $OUT"
[ "$status" = 0 ] || exit "$status"

if [ -n "$APK_DIR" ]; then
  mkdir -p "$APK_DIR"
  BUILD_TOOLS=$(dirname "$AAPT2")
  D8="$BUILD_TOOLS/d8"
  APKSIGNER="$BUILD_TOOLS/apksigner"
  ZIPALIGN="$BUILD_TOOLS/zipalign"
  KEYTOOL="$JAVA_HOME/bin/keytool"
  for f in "$D8" "$APKSIGNER" "$ZIPALIGN" "$KEYTOOL"; do
    [ -f "$f" ] || { echo "missing: $f" >&2; exit 2; }
  done

  # 1. classes -> dex (the reference's Makefile does this with d8 or r8).
  mkdir -p "$OUT/dex"
  find "$OUT" -name '*.class' > "$OUT/classes.txt"
  # `d8`/`apksigner` in build-tools are wrapper scripts around their jars, so they are run
  # directly (a `java -cp <script>` cannot find their main class - measured).
  JAVA_HOME="$JAVA_HOME" "$D8" --lib "$ANDROID_JAR" --min-api 21 --output "$OUT/dex" \
    $(cat "$OUT/classes.txt") || exit $?
  echo "dex: $(ls "$OUT/dex"/*.dex 2>/dev/null | wc -l | tr -d ' ') file(s), $(du -h "$OUT/dex/classes.dex" | cut -f1)"

  # 2. resources.ap_ + classes.dex -> apk
  UNSIGNED="$APK_DIR/emacs-unsigned.apk"
  cp "$OUT/resources.ap_" "$UNSIGNED"
  (cd "$OUT/dex" && "$JAVA_HOME/bin/jar" uf "$UNSIGNED" classes.dex) || exit $?
  "$ZIPALIGN" -f 4 "$UNSIGNED" "$APK_DIR/emacs-aligned.apk" || exit $?

  # 3. a debug key, generated once, and the signature (the reference signs too).
  KS="$APK_DIR/debug.keystore"
  [ -f "$KS" ] || "$KEYTOOL" -genkeypair -keystore "$KS" -storepass android -keypass android \
      -alias androiddebugkey -dname "CN=femacs debug" -keyalg RSA -validity 10000 >/dev/null 2>&1 || exit $?
  SIGNED="$APK_DIR/emacs.apk"
  JAVA_HOME="$JAVA_HOME" "$APKSIGNER" sign --ks "$KS" --ks-pass pass:android \
      --out "$SIGNED" "$APK_DIR/emacs-aligned.apk" > "$OUT/sign.log" 2>&1
  sign_status=$?
  if [ "$sign_status" != 0 ]; then
    echo "apksigner sign: exit $sign_status"
    tail -5 "$OUT/sign.log"
    exit "$sign_status"
  fi
  JAVA_HOME="$JAVA_HOME" "$APKSIGNER" verify --print-certs "$SIGNED" | head -3
  # Structural acceptance of the APK itself (short of a device): the manifest aapt2 wrote, the
  # dex it carries, and the signature - that is what can be checked without a JDK 7-capable
  # configure and without hardware (P-211).
  echo "== apk contents =="
  "$AAPT2" dump badging "$SIGNED" 2>/dev/null | grep -E "^(package|sdkVersion|targetSdkVersion|launchable-activity|application-label)" | head -5
  "$JAVA_HOME/bin/jar" tf "$SIGNED" 2>/dev/null | grep -E "^(classes[0-9]*\.dex|resources\.arsc|AndroidManifest\.xml)$" | sed 's/^/  member: /'
  echo "apk: $SIGNED ($(du -h "$SIGNED" | cut -f1)); native libraries pending the Android native build"
fi
exit "$status"
