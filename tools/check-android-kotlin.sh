#!/bin/sh
# Type-check the Android Kotlin shell against the platform's android.jar - offline.
#
# `docs/port-plan.md`'s platform row and DoD-6 need the Android leg to build.  The Kotlin
# sources (`platform/android/**/*.kt`, the port of `java/**/*.java`) do not need a full
# Android build to be *checked*: Android Studio ships a Kotlin compiler and a JDK, and the SDK
# ships `android.jar`, so the compile can run with nothing downloaded and nothing installed.
#
#   tools/check-android-kotlin.sh              # compile to a temp dir, print the class count
#   tools/check-android-kotlin.sh --keep DIR   # keep the output classes in DIR
#   tools/check-android-kotlin.sh --apk DIR    # also assemble and sign an APK in DIR
#
# `--apk` runs the rest of `emacs/java/Makefile.in`'s packaging: `d8` turns the classes - the
# port's own *and* the Kotlin runtime the sources call (`kotlin-stdlib.jar`, which a Java shell
# does not need and the port's Kotlin one does) - into `classes.dex`, `aapt2 link`'s archive and
# that dex are zipped into an APK, and `apksigner` signs it with a debug key `keytool` generates
# once.  The APK is built *without* the native
# libraries, which the port's Android native build will add (P-201); everything else is real.
#
# Environment overrides (all optional): STUDIO (the Android Studio bundle), ANDROID_HOME,
# ANDROID_API (default android-36).  Exit status is the compiler's.
set -u
REPO=$(cd "$(dirname "$0")/.." && pwd)
STUDIO=${STUDIO:-/Applications/Android Studio.app/Contents}
ANDROID_HOME=${ANDROID_HOME:-$HOME/Library/Android/sdk}
ANDROID_API=${ANDROID_API:-android-36}
OUT=""
OUT=""
KEEP=""
while [ $# -gt 0 ]; do
  case "$1" in
    --keep) KEEP=$2; shift 2 ;;
    --apk)  APK_DIR=$2; shift 2 ;;
    # `--native PATH` puts a shared library at `lib/arm64-v8a/libemacs.so` inside the APK, the
    # member the Android shell loads.  Without it the APK is the structural one of P-211.
    --native) NATIVE_SO=$2; shift 2 ;;
    # `--assets` packs C's `assets/{lisp,etc,bitmaps}` tree too (java/Makefile.in 200-297): the
    # Android build has no dump, so the port reads its Lisp from there (docs/android-app-readiness.md).
    --assets) ASSETS=1; shift ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done
OUT=""
APK_DIR=${APK_DIR:-}
NATIVE_SO=${NATIVE_SO:-}
ASSETS=${ASSETS:-0}

# Android Studio ships the complete CLI compiler (not just the IDE plugin): `kotlinc` next to
# its own JDK, which is all this check needs.
# The rule for this project is "the latest LTS JDK only, never an old JDK to work around a
# check".  A Homebrew `openjdk@25` is the newest LTS when it is installed; Android Studio's
# bundled JBR is the fallback (an LTS too, just older).  Both were measured to build the
# identical signed APK, so this only picks the default - `JAVA_HOME` still overrides it.
for _cand in /opt/homebrew/opt/openjdk@25 /usr/local/opt/openjdk@25; do
  if [ -x "$_cand/bin/javac" ]; then NEWEST_LTS_JDK=$_cand; break; fi
done
# Resolution order: an explicit `FEMACS_JAVA_HOME`, then the newest LTS JDK, then an ambient
# `JAVA_HOME`, then Studio's JBR.  The project rule is "the latest LTS JDK only", so an ambient
# older `JAVA_HOME` must not silently override it - it is a fallback, not a preference.
if [ -n "${FEMACS_JAVA_HOME:-}" ]; then JAVA_HOME=$FEMACS_JAVA_HOME
elif [ -n "${NEWEST_LTS_JDK:-}" ]; then JAVA_HOME=$NEWEST_LTS_JDK
elif [ -n "${JAVA_HOME:-}" ]; then :
else JAVA_HOME=$STUDIO/jbr/Contents/Home; fi
echo "jdk: $JAVA_HOME ($("$JAVA_HOME/bin/java" -version 2>&1 | head -1))"
KOTLINC="$STUDIO/plugins/Kotlin/kotlinc/bin/kotlinc"
STDLIB="$STUDIO/plugins/Kotlin/kotlinc/lib/kotlin-stdlib.jar"
ANDROID_JAR="$ANDROID_HOME/platforms/$ANDROID_API/android.jar"
AAPT2=$(ls "$ANDROID_HOME"/build-tools/*/aapt2 2>/dev/null | tail -1)

for f in "$KOTLINC" "$STDLIB" "$ANDROID_JAR" "$AAPT2"; do
  if [ ! -f "$f" ]; then
    echo "missing: $f" >&2
    echo "the Android leg needs Android Studio (for kotlinc and a JDK) and the SDK's $ANDROID_API" >&2
    exit 2
  fi
done

[ -n "$KEEP" ] && OUT=$KEEP
[ -n "$OUT" ] || OUT=$(mktemp -d /tmp/femacs-kt.XXXXXX)
mkdir -p "$OUT"

# `R` is generated by aapt2 from the manifest and `res/`, and the Kotlin sources use it, so the
# resource link runs first and its R.jar joins the classpath (P-199: without it every `R.style…`
# is an unresolved reference).
GEN="$OUT/gen"
mkdir -p "$GEN"
RES_ZIP="$OUT/res.zip"
"$AAPT2" compile --dir "$REPO/platform/android/res" -o "$RES_ZIP" || exit $?
# `android:debuggable` is C's `@ANDROID_DEBUGGABLE@` substitution (`java/AndroidManifest.xml.in`
# 222): the reference build sets it from its configuration, the port has no configure step, so it
# is off by default and `FEMACS_ANDROID_DEBUGGABLE=1` turns it on.  A debuggable APK is what makes
# bionic's `libc.debug.malloc.options` (guard pages) apply to the app's own process - the only
# on-device way to fault at the first out-of-bounds write instead of at its symptom (status 4.885).
MANIFEST="$REPO/platform/android/AndroidManifest.xml"
if [ "${FEMACS_ANDROID_DEBUGGABLE:-0}" = "1" ]; then
  MANIFEST="$OUT/AndroidManifest.debug.xml"
  sed 's/android:debuggable="false"/android:debuggable="true"/' \
    "$REPO/platform/android/AndroidManifest.xml" > "$MANIFEST" || exit 1
  grep -q 'android:debuggable="true"' "$MANIFEST" || {
    echo "FEMACS_ANDROID_DEBUGGABLE=1: the manifest has no debuggable attribute to flip" >&2
    exit 1; }
fi
"$AAPT2" link -o "$OUT/resources.ap_" -I "$ANDROID_JAR" \
  --manifest "$MANIFEST" --java "$GEN" "$RES_ZIP" || exit $?
mkdir -p "$OUT/rclasses"
R_JAVA=$(find "$GEN" -name R.java | head -1)
[ -n "$R_JAVA" ] || { echo "aapt2 did not write R.java" >&2; exit 3; }
# `R` is generated, and javac's bytecode target is not fixed by any source: on a JDK newer than
# the SDK's `d8` understands, javac's default emits a class file version `d8` refuses
# (`Unsupported class file major version 69` under JDK 25 - measured).  Every Android build pins
# this (Gradle pins `targetCompatibility`); the port pins it here so the dex input is the same
# whatever JDK builds it, and so the build can run on the latest LTS JDK.
JAVAC_RELEASE=${JAVAC_RELEASE:-17}
"$JAVA_HOME/bin/javac" --release "$JAVAC_RELEASE" -classpath "$ANDROID_JAR" -d "$OUT/rclasses" "$R_JAVA" || exit $?
(cd "$OUT/rclasses" && "$JAVA_HOME/bin/jar" cf "$OUT/R.jar" .) || exit $?
R_JAR="$OUT/R.jar"
echo "resources: R.jar built from $(find "$REPO/platform/android/res" -type f | wc -l | tr -d ' ') resource file(s)"

# The reference generates a class at build time (`EmacsConfig`, java/Makefile.in 411-424); the
# Kotlin sources name it, so the generator runs first and its file joins the compilation.
mkdir -p "$OUT/generated"
# The class names `libemacs.so`'s `(NEEDED)` closure, so the generator is given the linked
# library when the caller has one (without it the list is empty, which is the honest reading of
# "no Android library exists yet" - not a list of files, which is what the first version of the
# generator produced and what killed the app on the device, 4.706).
if [ -n "$NATIVE_SO" ]; then
  python3 "$REPO/tools/gen-emacs-config.py" --out "$OUT/generated" --library "$NATIVE_SO" || exit $?
else
  python3 "$REPO/tools/gen-emacs-config.py" --out "$OUT/generated" || exit $?
fi

FILES=$(find "$REPO/platform/android" "$OUT/generated" -name '*.kt' | sort)
COUNT=$(printf '%s\n' "$FILES" | grep -c .)
echo "compiling $COUNT Kotlin file(s) against $ANDROID_JAR"
# shellcheck disable=SC2086
# No `-no-stdlib`: the compiler's own standard library is what the sources expect, and it is
# part of the bundled kotlinc (passing `-no-stdlib` without a replacement makes every
# `kotlin.String` unreachable - measured).
JAVA_HOME="$JAVA_HOME" "$KOTLINC" -classpath "$ANDROID_JAR:$R_JAR" -d "$OUT" $FILES
status=$?
classes=$(find "$OUT" -name '*.class' | wc -l | tr -d ' ')
echo "kotlin: exit $status, $classes class file(s) in $OUT"
[ "$status" = 0 ] || exit "$status"

if [ -n "$APK_DIR" ]; then
  mkdir -p "$APK_DIR"
  BUILD_TOOLS=$(dirname "$AAPT2")
  D8="$BUILD_TOOLS/d8"
  APKSIGNER="$BUILD_TOOLS/apksigner"
  ZIPALIGN="$BUILD_TOOLS/zipalign"
  KEYTOOL="$JAVA_HOME/bin/keytool"
  for f in "$D8" "$APKSIGNER" "$ZIPALIGN" "$KEYTOOL"; do
    [ -f "$f" ] || { echo "missing: $f" >&2; exit 2; }
  done

  # 1. classes -> dex (the reference's Makefile does this with d8 or r8).
  mkdir -p "$OUT/dex"
  find "$OUT" -name '*.class' > "$OUT/classes.txt"
  # `d8`/`apksigner` in build-tools are wrapper scripts around their jars, so they are run
  # directly (a `java -cp <script>` cannot find their main class - measured).
  # `d8` puts its *inputs* into the dex, and the Kotlin sources call the standard library at
  # runtime: kotlinc emits `kotlin.jvm.internal.Intrinsics` into every non-null parameter check,
  # `kotlin.collections.*` into every list operation.  The compiler's own `kotlin-stdlib.jar`
  # therefore has to be an input alongside the app's classes.  Without it the APK installs and
  # launches and then dies in the first `ContentProvider.onCreate`
  # (`NoClassDefFoundError: Failed resolution of: Lkotlin/jvm/internal/Intrinsics` - measured on
  # the emulator, status 4.706; the reference's shell is Java, so this input has no counterpart
  # there and nothing else in the port's build supplies it).
  JAVA_HOME="$JAVA_HOME" "$D8" --lib "$ANDROID_JAR" --min-api 21 --output "$OUT/dex" \
    $(cat "$OUT/classes.txt") "$STDLIB" || exit $?
  echo "dex: $(ls "$OUT/dex"/*.dex 2>/dev/null | wc -l | tr -d ' ') file(s), $(du -h "$OUT/dex/classes.dex" | cut -f1)"
  # And assert it, so a dex built from the app's own classes alone cannot pass this check: the
  # type descriptor is a plain string in the dex string table.
  if ! LC_ALL=C grep -aq "Lkotlin/jvm/internal/Intrinsics;" "$OUT/dex/classes.dex"; then
    echo "the dex does not carry kotlin.jvm.internal.Intrinsics (the Kotlin runtime is missing)" >&2
    exit 3
  fi

  # 2. resources.ap_ + classes.dex -> apk
  UNSIGNED="$APK_DIR/emacs-unsigned.apk"
  cp "$OUT/resources.ap_" "$UNSIGNED"
  (cd "$OUT/dex" && "$JAVA_HOME/bin/jar" uf "$UNSIGNED" classes.dex) || exit $?
  # The native library, when the caller has one: same member path the Android shell's
  # `System.loadLibrary ("emacs")` looks for.
  if [ -n "$NATIVE_SO" ]; then
    [ -f "$NATIVE_SO" ] || { echo "missing native library: $NATIVE_SO" >&2; exit 2; }
    mkdir -p "$OUT/native/lib/arm64-v8a"
    cp "$NATIVE_SO" "$OUT/native/lib/arm64-v8a/libemacs.so"
    (cd "$OUT/native" && "$JAVA_HOME/bin/jar" uf "$UNSIGNED" lib/arm64-v8a/libemacs.so) || exit $?
    # `wrap.sh` is Android's documented hook for a *debuggable* app: the runtime execs
    # `lib/<abi>/wrap.sh <app_process command>` instead of the command itself, which is the only
    # way to hand bionic's malloc debugger (`libc.debug.malloc.options`) a process on this image -
    # setting the property alone produced no malloc-debug output at all (status 4.887).  Guard
    # pages then fault at the *first* out-of-bounds write and print its backtrace, which is what
    # the Android start-up hunt needs (status 4.888).
    if [ "${FEMACS_ANDROID_DEBUGGABLE:-0}" = "1" ]; then
      mkdir -p "$OUT/native/lib/arm64-v8a"
      cat > "$OUT/native/lib/arm64-v8a/wrap.sh" <<'WRAP'
#!/system/bin/sh
export libc.debug.malloc.options="guard backtrace"
exec "$@"
WRAP
      chmod 0755 "$OUT/native/lib/arm64-v8a/wrap.sh"
      (cd "$OUT/native" && zip -X -0 -q "$UNSIGNED" lib/arm64-v8a/wrap.sh) || exit $?
      echo "wrap.sh: ${FEMACS_ANDROID_DEBUGGABLE:+malloc debug (guard backtrace)}"
    fi
  fi
  if [ "$ASSETS" = 1 ]; then
    python3 "$REPO/tools/gen-android-assets.py" --out "$OUT/pack" >/dev/null || exit $?
    (cd "$OUT/pack" && "$JAVA_HOME/bin/jar" uf "$UNSIGNED" assets) || exit $?
    # `jar` deflates every entry, and Android's `AAsset_getBuffer` returns NULL for a compressed
    # asset - C's `android_init_assets` then takes its *silent* `if (!directory_tree) emacs_abort ()`
    # arm (C 1257), which reads on the device as a bare SIGSEGV with an `emacs_abort called`
    # tombstone (status 4.783).  The index has to be stored, so it is re-added with `-0`.
    (cd "$OUT/pack" && zip -X -0 -q "$UNSIGNED" assets/directory-tree) || exit $?
    echo "assets: $(cd "$OUT/pack" && find assets -type f | wc -l | tr -d ' ') file(s) packed"
  fi
  "$ZIPALIGN" -f 4 "$UNSIGNED" "$APK_DIR/emacs-aligned.apk" || exit $?
  # `wrap.sh` has to carry its executable mode *in the APK*, and both `zip` and `zipalign` drop
  # it (measured: the entry came out `-rw----`, Android ignored the hook, and the run looked
  # exactly like one without wrap.sh - status 4.888).  It is therefore written into the aligned
  # APK, before signing, with the mode in its external attributes.
  if [ "${FEMACS_ANDROID_DEBUGGABLE:-0}" = "1" ] && [ -f "$OUT/native/lib/arm64-v8a/wrap.sh" ]; then
    python3 - "$APK_DIR/emacs-aligned.apk" "$OUT/native/lib/arm64-v8a/wrap.sh" <<'PYWRAP' || exit 1
import sys, zipfile, os
apk, src = sys.argv[1], sys.argv[2]
data = open (src, "rb").read ()
tmp = apk + ".wrap"
zin = zipfile.ZipFile (apk)
zout = zipfile.ZipFile (tmp, "w")
for info in zin.infolist ():
    if info.filename == "lib/arm64-v8a/wrap.sh":
        continue
    zout.writestr (info, zin.read (info.filename))
info = zipfile.ZipInfo ("lib/arm64-v8a/wrap.sh")
info.external_attr = 0o100755 << 16
info.compress_type = zipfile.ZIP_STORED
zout.writestr (info, data)
zout.close (); zin.close ()
os.replace (tmp, apk)
PYWRAP
    python3 - "$APK_DIR/emacs-aligned.apk" <<'PYCHK' || exit 1
import sys, zipfile
z = zipfile.ZipFile (sys.argv[1])
modes = [oct (i.external_attr >> 16) for i in z.infolist () if i.filename.endswith ("wrap.sh")]
print ("wrap.sh mode:", modes)
raise SystemExit (0 if modes == ["0o100755"] else 1)
PYCHK
  fi

  # 3. a debug key, generated once, and the signature (the reference signs too).
  KS="$APK_DIR/debug.keystore"
  [ -f "$KS" ] || "$KEYTOOL" -genkeypair -keystore "$KS" -storepass android -keypass android \
      -alias androiddebugkey -dname "CN=femacs debug" -keyalg RSA -validity 10000 >/dev/null 2>&1 || exit $?
  SIGNED="$APK_DIR/emacs.apk"
  JAVA_HOME="$JAVA_HOME" "$APKSIGNER" sign --ks "$KS" --ks-pass pass:android \
      --out "$SIGNED" "$APK_DIR/emacs-aligned.apk" > "$OUT/sign.log" 2>&1
  sign_status=$?
  if [ "$sign_status" != 0 ]; then
    echo "apksigner sign: exit $sign_status"
    tail -5 "$OUT/sign.log"
    exit "$sign_status"
  fi
  JAVA_HOME="$JAVA_HOME" "$APKSIGNER" verify --print-certs "$SIGNED" | head -3
  # Structural acceptance of the APK itself (short of a device): the manifest aapt2 wrote, the
  # dex it carries, and the signature - that is what can be checked without a JDK 7-capable
  # configure and without hardware (P-211).
  echo "== apk contents =="
  "$AAPT2" dump badging "$SIGNED" 2>/dev/null | grep -E "^(package|sdkVersion|targetSdkVersion|launchable-activity|application-label)" | head -5
  "$JAVA_HOME/bin/jar" tf "$SIGNED" 2>/dev/null | grep -E "^(classes[0-9]*\.dex|resources\.arsc|AndroidManifest\.xml|lib/arm64-v8a/libemacs\.so)$" | sed 's/^/  member: /'
  if [ -n "$NATIVE_SO" ]; then
    echo "apk: $SIGNED ($(du -h "$SIGNED" | cut -f1)); native: lib/arm64-v8a/libemacs.so"
  else
    echo "apk: $SIGNED ($(du -h "$SIGNED" | cut -f1)); native libraries pending (pass --native PATH)"
  fi
fi
exit "$status"
