#!/usr/bin/env python3
"""The symbols the frozen build's own objects export, per reference source.

`tools/extract-abi.py`'s "invented exported symbol" rule reads the *text* of a reference
`.c` file and asks whether it defines a non-static function of the name a port's
`#[unsafe(no_mangle)]` / `#[unsafe(export_name = "...")]` claims.  For gnulib's wrapper
shape that text is not where the answer is: `lib/endian.c` is eleven lines that include the
header whose inline definitions the object exports (`T _rpl_endian_be16toh`), the `_gl_*`
names of `lib/malloc/*.c` come from a rename in that directory's header, and `lib/regcomp.c`
/`lib/regexec.c` are `#include`d by `lib/regex.c`, whose object carries them.  The frozen
build already answered the question authoritatively - its objects are on disk with the
symbols the linker sees - so this tool records that answer once, and the checker consults
the table instead of guessing from the source.

    python3 tools/gen-reference-symbols.py --write   # write the two tables
    python3 tools/gen-reference-symbols.py           # show what they would say

Two tables, both `<key>\\t<value>`:

* `docs/baseline/reference-symbols.tsv` - `<source path relative to emacs/>` -> a global
  symbol its object defines (Mach-O's leading `_` stripped).  The source comes from the
  object's own `deps/*.d`, so an object built from several translation units maps to each
  of them (`regex.o` answers for `regex.c`, `regcomp.c` and `regexec.c`).
* `docs/baseline/reference-renames.tsv` - `<name>` -> the `rpl_*` name the frozen build's
  generated headers rename it to.  This is the half that answers for a source the frozen
  build does not compile at all (`lib/gettimeofday.c`, `lib/pthread_sigmask.c`): the
  checker only accepts a rename whose left-hand name the reference defines itself.
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
BUILD = REPO / "build" / "emacs-ref"
SYMBOLS = REPO / "docs" / "baseline" / "reference-symbols.tsv"
RENAMES = REPO / "docs" / "baseline" / "reference-renames.tsv"

# `../../../emacs/lib/regex.c` - deps files spell the source relative to the object's dir.
SOURCE = re.compile(r"\.\./\.\./\.\./emacs/([A-Za-z0-9_./+-]+\.(?:c|m|cc))")
# A rename the generated header spells (`#   define pthread_sigmask rpl_pthread_sigmask`).
RENAME = re.compile(r"^#\s*define\s+(\w+)\s+(rpl_\w+)\s*$", re.M)
# nm's symbol kinds: T/S text, D/B data, C common, R read-only.  `U` is undefined.
DEFINED = set("TSDB C".replace(" ", ""))

HEADER = """# The symbols the frozen build's own objects export, per reference source.
# Generated by `tools/gen-reference-symbols.py --write` (from build/emacs-ref's objects and
# their deps files, the symbols the linker sees; Mach-O's leading `_` is stripped).  Read by
# `tools/extract-abi.py`'s invented-export rule: a port's `#[unsafe(no_mangle)]` /
# `export_name = "..."` is backed when this table names that symbol for that source, which is
# the authority `docs/status.md` 3.67 gives the object wherever one exists.  Generated data:
# do not edit by hand.
source\tsymbol
"""

RENAME_HEADER = """# The `rpl_*` names the frozen build's generated headers give a system name.
# Generated by `tools/gen-reference-symbols.py --write` from build/emacs-ref's generated
# headers (`lib/endian.h`, `lib/signal.h`, ...).  Read by `tools/extract-abi.py`'s rename
# chain: it answers for the sources the frozen build does not compile at all, and the checker
# still requires the left-hand name to be a function the reference itself defines.
# Generated data: do not edit by hand.
name\trpl_name
"""


def object_symbols(obj: Path) -> list[str]:
    out = subprocess.run(["nm", "-g", str(obj)], capture_output=True, text=True)
    if out.returncode != 0:
        return []
    names = []
    for line in out.stdout.split("\n"):
        parts = line.split()
        if len(parts) == 3 and parts[1] in DEFINED:
            names.append(parts[2][1:] if parts[2].startswith("_") else parts[2])
    return sorted(set(names))


def collect_symbols() -> dict[str, set[str]]:
    table: dict[str, set[str]] = {}
    for dirpath, _dirnames, filenames in os.walk(BUILD):
        for name in filenames:
            if not name.endswith(".d"):
                continue
            dep = Path(dirpath) / name
            # A deps file mirrors the object's own place with a `deps` segment inserted:
            # `lib/deps/malloc/dynarray_at_failure.d` describes `lib/malloc/dynarray_at_failure.o`.
            parts = list(dep.relative_to(BUILD).parts)
            if "deps" not in parts:
                continue
            parts.remove("deps")
            obj = BUILD.joinpath(*parts).with_suffix(".o")
            if not obj.is_file():
                continue
            try:
                text = dep.read_text(encoding="utf-8", errors="replace")
            except OSError:
                continue
            sources = set(SOURCE.findall(text))
            if not sources:
                continue
            symbols = object_symbols(obj)
            for src in sources:
                table.setdefault(src, set()).update(symbols)
    return table


def collect_renames() -> dict[str, set[str]]:
    table: dict[str, set[str]] = {}
    for dirpath, _dirnames, filenames in os.walk(BUILD):
        for name in filenames:
            if not name.endswith(".h"):
                continue
            try:
                text = (Path(dirpath) / name).read_text(encoding="utf-8", errors="replace")
            except OSError:
                continue
            for word, target in RENAME.findall(text):
                table.setdefault(word, set()).add(target)
    return table


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()
    if not BUILD.is_dir():
        print(f"gen-reference-symbols: {BUILD.relative_to(REPO)} is missing "
              f"(the tables are generated from the frozen build's objects)", file=sys.stderr)
        return 1
    symbols, renames = collect_symbols(), collect_renames()
    rows = sum(len(v) for v in symbols.values())
    print(f"{len(symbols)} source(s), {rows} symbol row(s); "
          f"{len(renames)} rename name(s), {sum(len(v) for v in renames.values())} row(s)")
    if not args.write:
        return 0
    SYMBOLS.write_text(HEADER + "".join(
        f"{src}\t{sym}\n" for src in sorted(symbols) for sym in sorted(symbols[src])),
        encoding="utf-8")
    RENAMES.write_text(RENAME_HEADER + "".join(
        f"{word}\t{target}\n" for word in sorted(renames) for target in sorted(renames[word])),
        encoding="utf-8")
    print(f"wrote {SYMBOLS.relative_to(REPO)} and {RENAMES.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
