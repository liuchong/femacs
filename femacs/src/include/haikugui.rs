// `gui.h`-shaped header - the header C calls `haikugui.h`, which `haikuterm.c`/`haikufns.c`
// include on a Haiku build, and which `dispextern.h` pulls in behind its `HAVE_HAIKU` arm.  The
// frozen target (darwin-arm64) does not build it, but the file has no `#if` of its own: every
// line below is unconditional C text, so the mirror carries every declaration (PORTING.md P-08;
// `tools/check-cond-eval.py src/haikugui.h` reports `0 conditions`).
//
// Names that repeat other headers' text: the X-compat block (the eleven `*Gravity`, the eight
// `*Value`, the ten `*Position` macros, `NativeRectangle`, `STORE_NATIVE_RECT`) is the same block
// `androidgui.h`/`nsgui.h`/`pgtkgui.h`/`w32gui.h` declare, and `Emacs_Cursor` is also
// `dispextern.h`'s `#ifndef HAVE_WINDOW_SYSTEM` typedef (`dispextern.rs` carries that arm).  C
// keeps the twins apart with its platform `#if`s; the port's mirrors meet in one crate when
// `xtask layout-check` compiles them, and that collision is recorded in
