/* Convert between the Emacs and native rectangle types.  */
// haikugui.h 47-58: C's bodies are comma expressions; Rust has no comma operator, so the port
// keeps the four assignments as a block.  The macros are used as statements (the value of C's
// comma expression is the last assignment, which no caller reads).
macro_rules! CONVERT_TO_EMACS_RECT {
  ($xr:expr, $nr:expr) =>
    { {
        ($xr).x = ($nr).x;
        ($xr).y = ($nr).y;
        ($xr).width = ($nr).width;
        ($xr).height = ($nr).height;
      } };
}
macro_rules! CONVERT_FROM_EMACS_RECT {
  ($xr:expr, $nr:expr) =>
    { {
        ($nr).x = ($xr).x;
        ($nr).y = ($xr).y;
        ($nr).width = ($xr).width;
        ($nr).height = ($xr).height;
      } };
}

// haikugui.h 59-63.
macro_rules! STORE_NATIVE_RECT {
  ($nr:expr, $px:expr, $py:expr, $pwidth:expr, $pheight:expr) =>
    { {
        ($nr).x = ($px);
        ($nr).y = ($py);
        ($nr).width = ($pwidth);
        ($nr).height = ($pheight);
      } };
}

