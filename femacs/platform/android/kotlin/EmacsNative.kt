/* The 69 methods below are the only consumers whose names are bound by the JNI **naming
   convention**, not by a lookup table: `src/android.h` 344 defines `NATIVE_NAME(name)`, which
   pastes the reference's own Java package into the symbol name, and the 69
   `NATIVE_NAME (…)` definitions live in three files - `android.c` 42, `androidterm.c` 22,
   `androidvfs.c` 5 - the same 69 names this class declares (measured set-equality, both ways).
   A JVM-visible `EmacsNative.<name>` must therefore exist as a *static native* method, which in
   Kotlin means a companion member with `@JvmStatic` (P-83 ④+⑪): measured with `javap -p -s`, the
   compiler emits `public static final native <ret> <name>(…)` on the outer class (and a
   delegating `invokestatic` method on the companion for Kotlin-level callers), so both the
   convention's binding and the in-tree callers work.

   Nullability is judged from the C bodies (P-83 ⑤): the natives whose implementation contains an
   explicit `return NULL` are declared nullable here - `getProcName`, `getSelectedText`,
   `getTextAfterCursor`, `getTextBeforeCursor`, `getSelection`, `getExtractedText`,
   `takeSnapshot` and `displayNameHash` (eight, each verified in its own C body); every other
   return is the reference's non-null platform type.  `setEmacsParams`' `classPath`/`emacsService`
   and `initEmacs`' `dumpFile` are nullable because the reference documents them as "or NULL"
   (its own `EmacsNoninteractive.main1` passes `null` for two of them, and
   `EmacsApplication.dumpFileName` is nullable in the port).

   One dependency of this file is **not** in the reference tree: `EmacsConfig` is generated by the
   build (`java/Makefile.in` 102 `CONFIG_FILE := $(builddir)/org/gnu/emacs/EmacsConfig.java`,
   written by the `cf-stamp-1` rule's `echo` of
   `public static final String[] EMACS_SHARED_LIBRARIES = {…};`), so the compile probe carries a
   stand-in for it exactly as it does for `R` (3.288 ④).  */
